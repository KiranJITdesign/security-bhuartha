def _configure_database():
    """Connect to Supabase PostgreSQL if DATABASE_URL is reachable within 3s, else SQLite."""
    db_url = os.getenv("DATABASE_URL", "").strip()
    is_test_run = len(sys.argv) > 1 and sys.argv[1] == "test"

    if not db_url or "[YOUR-PASSWORD]" in db_url or "[YOUR-PROJECT-REF]" in db_url or is_test_run:
        return _SQLITE_DB, "LOCAL_FALLBACK", "DB: LOCAL FALLBACK"

    try:
        import psycopg2

        conn = psycopg2.connect(db_url, connect_timeout=3)
        conn.close()
        pg_conf = dj_database_url.parse(db_url, conn_max_age=600, ssl_require=True)
        pg_conf.setdefault("OPTIONS", {})["connect_timeout"] = 3
        return pg_conf, "SUPABASE_LIVE", "DB: SUPABASE LIVE"
    except Exception as exc:
        logger.warning("Supabase unreachable or unconfigured (%s); using local SQLite fallback.", exc)
        return _SQLITE_DB, "LOCAL_FALLBACK", "DB: LOCAL FALLBACK"


_ACTIVE_DB_CONF, ACTIVE_DB_MODE, ACTIVE_DB_LABEL = _configure_database()

